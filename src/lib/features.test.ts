import { describe, expect, it } from 'vitest'
import { detectSlicer, F, mapFeature, parseDuration } from './features'

describe('mapFeature', () => {
  it.each([
    ['WALL-OUTER', F.OuterWall],
    ['WALL-INNER', F.InnerWall],
    ['SKIN', F.Skin],
    ['FILL', F.Infill],
    ['SUPPORT-INTERFACE', F.Support],
    ['SKIRT', F.Skirt],
    ['PRIME-TOWER', F.PrimeTower],
    ['External perimeter', F.OuterWall],
    ['Perimeter', F.InnerWall],
    ['Overhang perimeter', F.Bridge],
    ['Internal infill', F.Infill],
    ['Solid infill', F.Skin],
    ['Top solid infill', F.Skin],
    ['Gap fill', F.GapFill],
    ['Wipe tower', F.PrimeTower],
    ['Outer wall', F.OuterWall],
    ['Sparse infill', F.Infill],
    ['Bottom surface', F.Skin],
    ['outer perimeter', F.OuterWall],
    ['inner perimeter', F.InnerWall],
    ['Custom', F.Unknown],
  ])('%s', (name, id) => expect(mapFeature(name)).toBe(id))
})

describe('detectSlicer', () => {
  it('recognises the common slicers', () => {
    expect(detectSlicer('generated by PrusaSlicer 2.7.1 on 2024-01-01')).toEqual({ slicer: 'PrusaSlicer', version: '2.7.1' })
    expect(detectSlicer('generated by OrcaSlicer 2.1.0')?.slicer).toBe('OrcaSlicer')
    expect(detectSlicer('Generated with Cura_SteamEngine 5.4.0')).toEqual({ slicer: 'Cura', version: '5.4.0' })
    expect(detectSlicer('FLAVOR:Marlin')?.slicer).toBe('Cura')
    expect(detectSlicer('G-Code generated by Simplify3D(R) Version 4.1.2')).toEqual({ slicer: 'Simplify3D', version: '4.1.2' })
    expect(detectSlicer('hello')).toBeNull()
  })
})

describe('parseDuration', () => {
  it('reads slicer durations', () => {
    expect(parseDuration('1h 2m 3s')).toBe(3723)
    expect(parseDuration('2d 3h')).toBe(2 * 86400 + 3 * 3600)
    expect(parseDuration('45s')).toBe(45)
    expect(parseDuration('nothing')).toBeNull()
  })
})
