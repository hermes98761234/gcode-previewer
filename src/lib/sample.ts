/** Built-in sample files, generated in code so the app has something to show without any download. */

const f = (n: number, d = 3) => {
  const s = n.toFixed(d)
  return s === '-0.000' ? '0.000' : s
}

/** A small twisted vase, sliced PrusaSlicer-style: ~40 mm tall, 0.2 mm layers, relative extrusion. */
export function sampleVase(): string {
  const out: string[] = []
  const cx = 110
  const cy = 110
  const layerH = 0.2
  const layers = 200
  const width = 0.45
  const ePerMm = (width * layerH) / (Math.PI * (1.75 / 2) ** 2)
  const radius = (z: number, a: number) => {
    const body = 13 + 6 * Math.sin(z * 0.16 + 0.3) - 4 * (z / 40) ** 2
    return body * (1 + 0.05 * Math.cos(6 * a + z * 0.18))
  }
  out.push(
    '; generated by PrusaSlicer 2.7.0 (sample generated in your browser)',
    '; filament_diameter = 1.75',
    '; filament_density = 1.24',
    'M107', 'M115 U3.12.0', 'G90', 'M83', 'M204 S1000', 'G28', 'G1 Z5 F5000',
    'M104 S215', 'M140 S60',
    '; purge line',
    'G92 E0', 'G1 X72 Y80 F9000', 'G1 Z0.2 F720',
    `G1 X72 Y140 E${f(60 * ePerMm * 1.2, 4)} F1200`,
    `G1 X72.4 Y140 E${f(0.4 * ePerMm, 4)}`,
    `G1 X72.4 Y80 E${f(60 * ePerMm * 1.2, 4)}`,
    'G1 E-0.8 F2100',
  )
  let cur: [number, number] = [72.4, 80]
  const travel = (x: number, y: number, z: number) => {
    out.push(`G1 Z${f(z + 0.4)} F9000`, `G1 X${f(x)} Y${f(y)} F9000`, `G1 Z${f(z)} F9000`, 'G1 E0.8 F1800')
    cur = [x, y]
  }
  const retract = () => out.push('G1 E-0.8 F2100')
  const line = (x: number, y: number, feed?: number) => {
    const l = Math.hypot(x - cur[0], y - cur[1])
    out.push(`G1 X${f(x)} Y${f(y)} E${f(l * ePerMm, 5)}${feed ? ` F${feed}` : ''}`)
    cur = [x, y]
  }
  for (let li = 0; li < layers; li++) {
    const z = (li + 1) * layerH
    out.push(';LAYER_CHANGE', `;Z:${f(z)}`, `;HEIGHT:${f(layerH)}`)
    out.push(`G1 Z${f(z)} F720`)
    const ring = (inset: number, steps: number, feed: number) => {
      for (let s = 0; s <= steps; s++) {
        const a = (s / steps) * Math.PI * 2
        const r = radius(z, a) - inset
        const x = cx + r * Math.cos(a)
        const y = cy + r * Math.sin(a)
        if (s === 0) {
          travel(x, y, z)
          out.push(`G1 F${feed}`)
        } else line(x, y)
      }
      retract()
    }
    if (li === 0) {
      out.push(';TYPE:Skirt')
      const r0 = radius(z, 0) + 6
      for (let k = 0; k < 2; k++) {
        const steps = 90
        for (let s = 0; s <= steps; s++) {
          const a = (s / steps) * Math.PI * 2
          const x = cx + (r0 + k * 0.5) * Math.cos(a)
          const y = cy + (r0 + k * 0.5) * Math.sin(a)
          if (s === 0) travel(x, y, z)
          else line(x, y, 1500)
        }
        retract()
      }
    }
    if (li < 5) {
      out.push(';TYPE:Solid infill')
      const r = radius(z, 0) - 1.2
      let dir = 1
      for (let y = -r + 0.3; y <= r - 0.3; y += 0.8) {
        const half = Math.sqrt(Math.max(0, r * r - y * y)) * 0.92
        const [xa, xb] = dir > 0 ? [-half, half] : [half, -half]
        travel(cx + xa, cy + y, z)
        line(cx + xb, cy + y, 3000)
        retract()
        dir = -dir
      }
    }
    out.push(';TYPE:Perimeter')
    ring(0.5, 120, 2700)
    out.push(';TYPE:External perimeter')
    ring(0, 120, 1800)
    if (li >= 5 && li % 20 === 0) {
      out.push(';TYPE:Internal infill')
      const r = radius(z, 0) - 1.4
      travel(cx - r * 0.7, cy, z)
      line(cx + r * 0.7, cy, 3600)
      retract()
    }
  }
  out.push('M104 S0', 'M140 S0', 'G1 Z45 F720', 'G1 X10 Y200 F9000', 'M84', '; estimated printing time (normal mode) = 0h 0m 0s')
  return out.join('\n') + '\n'
}

/** A CNC job: a rounded 60x40 pocket in three passes, a helical-bored hole and a profile cut with R arcs. */
export function sampleCnc(): string {
  const out: string[] = []
  out.push(
    '(Sample CNC job generated in your browser)',
    '(6 mm end mill: rounded pocket, helical hole, profile)',
    'G21 G90 G17 G94',
    'M3 S12000',
    'G0 Z5',
  )
  const W = 60
  const H = 40
  const tool = 3
  const step = 4
  const depthPerPass = 2
  const depth = 6
  for (let pass = 1; pass <= depth / depthPerPass; pass++) {
    const z = -pass * depthPerPass
    out.push(`(pocket pass ${pass})`)
    let first = true
    for (let k = 0; ; k++) {
      const d = tool + k * step
      const x0 = d, y0 = d, x1 = W - d, y1 = H - d
      if (y1 - y0 < 1) break
      const r = Math.max(0, 3 - k * step)
      if (first) {
        out.push(`G0 X${f(x0 + r)} Y${f(y0)}`, 'G0 Z1', `G1 Z${f(z)} F150`)
        first = false
      } else out.push(`G1 X${f(x0 + r)} Y${f(y0)} F600`)
      out.push(`G1 X${f(x1 - r)} Y${f(y0)} F600`)
      if (r > 0) out.push(`G3 X${f(x1)} Y${f(y0 + r)} I0 J${f(r)}`)
      out.push(`G1 X${f(x1)} Y${f(y1 - r)}`)
      if (r > 0) out.push(`G3 X${f(x1 - r)} Y${f(y1)} I${f(-r)} J0`)
      out.push(`G1 X${f(x0 + r)} Y${f(y1)}`)
      if (r > 0) out.push(`G3 X${f(x0)} Y${f(y1 - r)} I0 J${f(-r)}`)
      out.push(`G1 X${f(x0)} Y${f(y0 + r)}`)
      if (r > 0) out.push(`G3 X${f(x0 + r)} Y${f(y0)} I${f(r)} J0`)
    }
    out.push('G0 Z5')
  }
  out.push('(helical bore, 12 mm hole)', 'G0 X-20 Y20', 'G0 Z1', 'G1 X-17 Y20 Z0 F200')
  for (let z = -1.5; z >= -7.5; z -= 1.5) out.push(`G2 X-17 Y20 Z${f(z)} I-3 J0 F300`)
  out.push('G2 X-17 Y20 I-3 J0 F300', 'G0 Z5')
  out.push('(profile around the part, R arcs)', 'G0 X-5 Y0', 'G1 Z-3 F150', 'G1 X65 Y0 F500')
  out.push('G3 X70 Y5 R5', 'G1 X70 Y35', 'G3 X65 Y40 R5', 'G1 X-5 Y40', 'G3 X-10 Y35 R5', 'G1 X-10 Y5', 'G3 X-5 Y0 R5')
  out.push('G0 Z10', 'M5', 'G0 X0 Y0', 'M30')
  return out.join('\n') + '\n'
}

export type SampleId = 'vase' | 'cnc'
export const SAMPLES: Record<SampleId, { name: string; generate: () => string }> = {
  vase: { name: 'sample-vase.gcode', generate: sampleVase },
  cnc: { name: 'sample-pocket.nc', generate: sampleCnc },
}
