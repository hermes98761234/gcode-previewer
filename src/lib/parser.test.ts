import { describe, expect, it } from 'vitest'
import { F } from './features'
import { GCodeParser, parseGCode } from './parser'
import { FLAG } from './toolpath'

const seg = (tp: ReturnType<typeof parseGCode>, i: number) => Array.from(tp.pos.subarray(i * 6, i * 6 + 6))

describe('moves and modes', () => {
  it('handles absolute and relative positioning (G90/G91)', () => {
    const tp = parseGCode('G90\nG1 X10 Y10\nG91\nG1 X5 Y-5\nG90\nG1 X0 Y0\n')
    expect(tp.count).toBe(3)
    expect(seg(tp, 1)).toEqual([10, 10, 0, 15, 5, 0])
    expect(seg(tp, 2)).toEqual([15, 5, 0, 0, 0, 0])
  })

  it('applies inches (G20) to coordinates and feed', () => {
    const tp = parseGCode('G20\nG1 X1 F60\n')
    expect(tp.pos[3]).toBeCloseTo(25.4)
    expect(tp.feed[0]).toBeCloseTo(25.4)
    expect(tp.meta.usesInches).toBe(true)
  })

  it('converts F (mm/min) to mm/s', () => {
    expect(parseGCode('G1 X1 F3000\n').feed[0]).toBe(50)
  })

  it('tracks absolute extrusion totals (M82) and G92 E0 resets', () => {
    const tp = parseGCode('M82\nG1 X10 E1\nG1 X20 E2.5\nG92 E0\nG1 X30 E1\nG1 X40 E3\n')
    expect(Array.from(tp.ext)).toEqual([1, 1.5, 1, 2])
    expect(Array.from(tp.flags).every((f) => f === FLAG.Extrude)).toBe(true)
  })

  it('tracks relative extrusion (M83)', () => {
    const tp = parseGCode('M83\nG1 X10 E0.5\nG1 X20 E0.5\nG1 E-2\nG1 E2\n')
    expect(Array.from(tp.ext)).toEqual([0.5, 0.5, -2, 2])
    expect(tp.flags[2]).toBe(FLAG.EOnly)
  })

  it('treats an absolute-E retract as a negative extruder-only move', () => {
    const tp = parseGCode('G1 X10 E5\nG1 E3\nG0 X50\nG1 E5\n')
    expect(tp.flags[1]).toBe(FLAG.EOnly)
    expect(tp.ext[1]).toBeCloseTo(-2)
    expect(tp.flags[2]).toBe(FLAG.Rapid)
    expect(tp.ext[3]).toBeCloseTo(2)
  })

  it('shifts coordinates with G92 without moving', () => {
    const tp = parseGCode('G1 X10\nG92 X0\nG1 X5\n')
    expect(tp.count).toBe(2)
    expect(seg(tp, 1)).toEqual([10, 0, 0, 15, 0, 0])
  })

  it('keeps the last motion mode for coordinate-only lines and ignores comments and checksums', () => {
    const tp = parseGCode('G1 X1 (inline comment) F600\nX2 ; trailing\nN10 Y3*57\n')
    expect(tp.count).toBe(3)
    expect(seg(tp, 2)).toEqual([2, 0, 0, 2, 3, 0])
  })

  it('implements firmware retract with M207', () => {
    const tp = parseGCode('M207 S1.5 F1200\nG10\nG0 X10\nG11\n')
    expect(tp.ext[0]).toBeCloseTo(-1.5)
    expect(tp.feed[0]).toBeCloseTo(20)
    expect(tp.ext[2]).toBeCloseTo(1.5)
  })

  it('classifies printing, travel and feed moves per machine type', () => {
    const printer = parseGCode('G1 X10 E1\nG1 X20\nG0 X30\n')
    expect(printer.meta.machine).toBe('printer')
    expect(printer.flags[0]).toBe(FLAG.Extrude)
    expect(printer.flags[1]).toBe(FLAG.Feed)
    const cnc = parseGCode('G0 X10\nG1 Z-1 F100\nG1 X20\n')
    expect(cnc.meta.machine).toBe('cnc')
    expect(cnc.type[2]).toBe(F.Cut)
  })

  it('splits arcs into segments and spreads extrusion over them', () => {
    const tp = parseGCode('G1 X10 Y0\nG3 X0 Y10 I-10 J0 E3 F1200\n')
    expect(tp.count).toBeGreaterThan(10)
    let e = 0
    for (let i = 1; i < tp.count; i++) e += tp.ext[i]
    expect(e).toBeCloseTo(3, 4)
    expect(Array.from(tp.pos.subarray((tp.count - 1) * 6 + 3, tp.count * 6))).toEqual([0, 10, 0])
  })

  it('streams across arbitrary chunk boundaries', () => {
    const text = 'G1 X10 F600\nG1 Y10\nG1 X0\n'
    const p = new GCodeParser()
    for (const ch of text) p.feed(ch)
    const tp = p.finish()
    expect(tp.count).toBe(3)
    expect(seg(tp, 2)).toEqual([10, 10, 0, 0, 10, 0])
  })
})

describe('layers, features and metadata', () => {
  it('uses slicer layer markers and feature comments', () => {
    const tp = parseGCode(
      '; generated by PrusaSlicer 2.7.0\n;LAYER_CHANGE\n;Z:0.2\n;TYPE:External perimeter\nG1 X10 E1\n;TYPE:Internal infill\nG1 X20 E2\n;LAYER_CHANGE\nG1 Z0.4\n;TYPE:Perimeter\nG1 X30 E3\n',
    )
    expect(tp.meta.slicer).toBe('PrusaSlicer')
    expect(tp.layerCount).toBe(2)
    expect(Array.from(tp.layerStart)).toEqual([0, 2, 4])
    expect(tp.type[0]).toBe(F.OuterWall)
    expect(tp.type[1]).toBe(F.Infill)
    expect(tp.type[3]).toBe(F.InnerWall)
  })

  it('reads Cura markers and time estimate', () => {
    const tp = parseGCode(';FLAVOR:Marlin\n;TIME:123\n;LAYER:0\n;TYPE:WALL-OUTER\nG1 X1 E1\n;LAYER:1\nG1 X2 E1\n')
    expect(tp.meta.slicer).toBe('Cura')
    expect(tp.meta.slicerEstimate).toBe(123)
    expect(tp.layerCount).toBe(2)
  })

  it('falls back to Z changes for layers without a slicer', () => {
    const tp = parseGCode('G1 Z0.2 F1000\nG1 X10 E1\nG1 Z0.4\nG1 X0 E2\nG1 Z0.6\nG1 X10 E3\n')
    expect(tp.layerCount).toBe(3)
    expect(tp.layerZ[0]).toBeCloseTo(0.2)
    expect(tp.layerZ[2]).toBeCloseTo(0.6)
  })

  it('layers a CNC file by cutting depth', () => {
    const tp = parseGCode('G21 G90\nG0 Z5\nG0 X0 Y0\nG1 Z-1 F100\nG1 X10\nG1 Z-2\nG1 X0\n')
    expect(tp.layerCount).toBe(2)
    expect(tp.layerZ[0]).toBeCloseTo(-1)
    expect(tp.layerZ[1]).toBeCloseTo(-2)
  })

  it('computes the bounding box over printed moves only', () => {
    const tp = parseGCode('G0 X-50 Y-50\nG0 X0 Y0\nG1 X1 Y0 E0.1\nG1 X10 Y20 Z3 E0.2\n')
    expect(tp.bounds.min).toEqual([0, 0, 0])
    expect(tp.bounds.max).toEqual([10, 20, 3])
  })

  it('picks up filament diameter from slicer config comments', () => {
    const tp = parseGCode('; generated by PrusaSlicer 2.7.0\nG1 X1 E1\n; filament_diameter = 1.75,1.75\n; filament_density = 1.24\n')
    expect(tp.meta.filamentDiameter).toBe(1.75)
    expect(tp.meta.filamentDensity).toBe(1.24)
  })

  it('parses a dwell and the tool number', () => {
    const tp = parseGCode('T1\nG4 S2\nG1 X1 E1\n')
    expect(tp.flags[0]).toBe(FLAG.Dwell)
    expect(tp.ext[0]).toBe(2)
    expect(tp.tool[1]).toBe(1)
  })
})
